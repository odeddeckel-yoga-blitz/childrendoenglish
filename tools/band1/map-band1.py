#!/usr/bin/env python3
"""Map OUR words to the Ministry of Education's Band I levels → src/data/band1.js.

The Ministry's Band I file (LexicalBand1.xlsx, "Lexical Pre-Band I & Band I",
https://meyda.education.gov.il/files/Mazkirut_Pedagogit/English/CurriculumFilesAugust21/LexicalBand1.xlsx,
updated 2023-01-26) says no part of it may be reproduced, transmitted,
translated or stored without written permission. So this script reads it from
a local path you download yourself, and writes ONLY a level flag for words
CDE already has (app words by id, unit-only words by their English text). The
list itself, its order, its meanings and its other entries never enter the repo.
Owner decision 2026-10-29: "map it, dont copy it".

Usage:  python3 tools/band1/map-band1.py /path/to/LexicalBand1.xlsx   (needs openpyxl)
Then:   npm run build  (pages: scripts/build-band1-pages.mjs)
Matching is by word form (an entry "a/b" counts for a and b; parentheses dropped),
so a homograph (fly the insect vs fly the verb) is tagged by form, not meaning.
"""
import json, re, subprocess, sys
from pathlib import Path
import openpyxl

ROOT = Path(__file__).resolve().parents[2]
SHEETS = {'Pre-Band I': 'pre', 'Band I Core I': 'c1', 'Band I Core II': 'c2'}
norm = lambda s: re.sub(r'\s+', ' ', re.sub(r'\(.*?\)', '', s.lower())).strip()

wb = openpyxl.load_workbook(sys.argv[1], read_only=True)
level = {}
for sheet, tag in SHEETS.items():
    for row in wb[sheet].iter_rows(values_only=True):
        e = row[0]
        if not isinstance(e, str) or not e.strip() or e.strip() in ('Entry', 'Phrasal verbs and chunks') or e.strip().isupper():
            continue
        for part in e.split('/'):
            level.setdefault(norm(part), tag)  # first (lowest) band wins

ours = json.loads(subprocess.run(['node', '-e', """
Promise.all([import('./src/data/words.js'), import('./src/data/units.js')]).then(([w, u]) => {
  const app = w.WORDS.map((x) => [x.id, x.word]);
  const unitOnly = [...new Set(u.UNITS.filter((x) => !x.test).flatMap((x) => x.words.filter((y) => !y.wordId).map((y) => y.en)))];
  console.log(JSON.stringify({ app, unitOnly }));
});"""], cwd=ROOT, capture_output=True, text=True, check=True).stdout)

app = {wid: level[norm(word)] for wid, word in ours['app'] if norm(word) in level}
text = {norm(en): level[norm(en)] for en in ours['unitOnly'] if norm(en) in level}
out = ROOT / 'src' / 'data' / 'band1.js'
out.write_text(f"""// GENERATED by tools/band1/map-band1.py — do not edit by hand.
// Which of OUR words are on the Ministry of Education's Band I list, and at
// which level: pre = Pre-Band I, c1 = Band I Core I, c2 = Band I Core II.
// Source: LexicalBand1.xlsx (file says: updated 2023-01-26),
// {'https://meyda.education.gov.il/files/Mazkirut_Pedagogit/English/CurriculumFilesAugust21/LexicalBand1.xlsx'}
// A mapping only: the Ministry list is not stored or reproduced here.
export const BAND1_SOURCE = 'https://meyda.education.gov.il/files/Mazkirut_Pedagogit/English/CurriculumFilesAugust21/LexicalBand1.xlsx';
export const BAND1_TOTAL = {len(level)}; // Band I items (word forms) in the source, for the coverage line
export const BAND1_BY_ID = {json.dumps(app, ensure_ascii=False, sort_keys=True)};
export const BAND1_BY_TEXT = {json.dumps(text, ensure_ascii=False, sort_keys=True)};
""")
print(f'app words tagged {len(app)} · unit-only words tagged {len(text)} · band items {len(level)} → {out.relative_to(ROOT)}')
