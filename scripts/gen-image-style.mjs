#!/usr/bin/env node
// Picture style per word (owner 11-07: ONE STYLE PER QUIZ ROUND — a lone emoji among photos, or a lone photo among
// drawings, gives the answer away). Generated from scripts/IMAGE_SOURCES.json so a picture swap can't leave a game's
// hand-kept style list stale. Drawn = our own drawings, Twemoji, Fluent Emoji, plus Commons files that are drawings
// (checked by eye). Everything else is a photo.
//   node scripts/gen-image-style.mjs        → src/data/imageStyle.js (app) + public/games/image-style.js (games)
// src/__tests__/imageStyle.test.js fails when either file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DRAWN_SOURCES = ['own', 'twemoji', 'fluent-emoji'];
export const DRAWN_COMMONS = ['table', 'pencil', 'microscope', 'folder'];   // Commons files that are drawings (11-07)

export function drawnIds() {
  const src = JSON.parse(readFileSync(join(ROOT, 'scripts/IMAGE_SOURCES.json'), 'utf8'));
  return [...new Set([...Object.entries(src).filter(([, v]) => DRAWN_SOURCES.includes(v?.source)).map(([k]) => k), ...DRAWN_COMMONS])].sort();
}

export function render() {
  const ids = drawnIds();
  const app = `// GENERATED by scripts/gen-image-style.mjs from scripts/IMAGE_SOURCES.json — do not edit by hand.\n` +
    `// Words whose picture is a drawing / emoji; every other word's picture is a photo.\n` +
    `export const DRAWN = new Set(${JSON.stringify(ids)});\n` +
    `export const pictureStyle = (id) => (DRAWN.has(id) ? 'drawn' : 'photo');\n`;
  const games = `/* GENERATED by scripts/gen-image-style.mjs from scripts/IMAGE_SOURCES.json — do not edit by hand.\n` +
    ` * Words whose picture is a drawing / emoji (one style per round: never mix styles among answer options). */\n` +
    `window.CDE_DRAWN = ${JSON.stringify(ids)};\n`;
  return { app, games };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { app, games } = render();
  writeFileSync(join(ROOT, 'src/data/imageStyle.js'), app);
  writeFileSync(join(ROOT, 'public/games/image-style.js'), games);
  console.log(`image style: ${drawnIds().length} drawn words`);
}
