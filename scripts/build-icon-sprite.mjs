#!/usr/bin/env node
// Drawn interface icons (owner 11-04: emoji icons made the site read as AI-built). One line-icon set everywhere: the
// React app imports lucide-react directly; static pages and the games use this sprite, built from the SAME Lucide
// shapes (lucide-react's own icon nodes, ISC licence — notice on /image-credits/):
//   <svg class="ic" aria-hidden="true" style="width:1.15em;height:1.15em;vertical-align:-.2em"><use href="/icons.svg#i-play"/></svg>
// Run after adding a name: node scripts/build-icon-sprite.mjs  (writes public/icons.svg; commit it).
import { writeFileSync } from 'node:fs';

export const ICON_NAMES = [
  'apple', 'arrow-left', 'arrow-right', 'arrow-up', 'backpack', 'blocks', 'book-open', 'brain', 'bus', 'calendar-days', 'camera', 'car',
  'check', 'circle-check', 'circle-x', 'clipboard-list', 'crown', 'dices', 'ear', 'file-text', 'flame', 'gamepad-2',
  'gift', 'hammer', 'hand', 'hash', 'headphones', 'heart', 'hourglass', 'house', 'image', 'layers', 'library', 'lightbulb',
  'lock', 'magnet', 'map', 'maximize', 'medal', 'music', 'notebook-pen', 'package', 'palette', 'party-popper', 'paw-print',
  'pencil', 'pin', 'play', 'pointer', 'printer', 'projector', 'puzzle', 'rainbow', 'refresh-cw', 'repeat', 'rocket',
  'rotate-ccw', 'scroll', 'search', 'shield', 'shirt', 'smartphone', 'smile', 'sparkles', 'star', 'swords', 'tag',
  'target', 'timer', 'trees', 'triangle-alert', 'trophy', 'turtle', 'type', 'users', 'volleyball', 'volume-2', 'volume-x', 'wand-sparkles',
  'wind', 'x', 'zap',
];

const esc = (v) => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const symbols = [];
for (const name of ICON_NAMES) {
  const { __iconNode } = await import(`../node_modules/lucide-react/dist/esm/icons/${name}.js`);
  const body = __iconNode.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key')
    .map(([k, v]) => `${k}="${esc(v)}"`).join(' ')}/>`).join('');
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24"><g fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</g></symbol>`);
}
writeFileSync(new URL('../public/icons.svg', import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n<!-- Lucide icons (lucide.dev), ISC License: Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2026 as part of Feather (MIT). All other copyright (c) for Lucide are held by Lucide Contributors 2026. Permission to use, copy, modify, and/or distribute this software for any purpose with or without fee is hereby granted, provided that the above copyright notice and this permission notice appear in all copies. Generated by scripts/build-icon-sprite.mjs -->\n${symbols.join('\n')}\n</svg>\n`);
console.log(`icons.svg: ${symbols.length} icons`);
